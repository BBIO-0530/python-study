# ------------------------------------------
# 1. 함수 (Functions)
# ------------------------------------------
# 함수는 코드의 재사용성과 가독성을 높이는 핵심 기능입니다.
# [보충] 똑같은 코드를 여러 번 치기 귀찮을 때, 하나의 '블록'으로 만들어두고 이름만 불러서 쓰는 개념입니다.

def birthday():
    print("생일 축하해 :)")

birthday()  # 함수 호출(실행)

# 매개변수(입력값)가 있는 함수
def a(d):
    c = input("생일을 입력해주세요! (예: 3/15) : ")
    if c == "3/15":
        print(f"생일 축하합니다 {d}님!! :)")
    else:
        print(f"오늘은 {d}님의 생일이 아니군요!") # [보충] 생일이 아닐 때의 예외 처리도 살짝 추가

a("손")


# ------------------------------------------
# 2. 반환값이 있는 함수 (return)
# ------------------------------------------
# 함수의 결과값을 호출한 곳으로 다시 돌려주고 싶을 때 'return'을 사용합니다.
# [보충] print()는 화면에 보여주기만 할 뿐, 그 값을 다른 계산에 쓸 수는 없습니다. return을 해야 값을 변수에 저장하고 재활용할 수 있어요!
def add(a, b):
    c = a + b
    print(f"안에서 계산된 값: {c}")
    return c

d = add(3, 2)
print(f"밖으로 반환된 값: {d}") 


# ------------------------------------------
# 3. 기본값이 있는 매개변수 (Default Parameters)
# ------------------------------------------
# 매개변수에 기본값을 미리 정해두면, 값을 넘겨주지 않았을 때 기본값이 자동으로 들어갑니다.
def m(name, greet="안녕하세요!"):
    print(f"{greet}, {name}님!")

m("면희", "환영합니다")  # 값을 넘겨주면 "환영합니다"로 덮어씌워짐
m("원도어")              # [보충] 두 번째 값을 안 주면 기본값인 "안녕하세요!"가 출력됨


# ------------------------------------------
# 4. 가변 매개변수 (*args, **kwargs)
# ------------------------------------------
# 매개변수가 몇 개 들어올지 모를 때 사용합니다. (*몇 개의 변수를 사용하든 괜찮다*)

# 4.1 *args (Arguments): 여러 개의 값을 '튜플' 형태로 받습니다.
def print_numbers(*args):
    for number in args:
        print(number)

print_numbers(1, 2, 3, 4, 5)

# 4.2 [보충] **kwargs (Keyword Arguments): 키워드=값 형태로 여러 개를 '딕셔너리'로 받습니다.
def print_info(**kwargs):
    for key, value in kwargs.items():
        print(f"{key}: {value}")

print_info(name="성호", age=22, role="맏형")


# ------------------------------------------
# 5. 람다 함수 (Lambda)
# ------------------------------------------
# def를 쓰기엔 너무 간단한 기능을 만들 때 사용하는 '이름이 없는' 한 줄짜리 함수입니다.
add1 = lambda x, y: x + y 
print(add1(500, 30))


