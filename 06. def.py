# 6. 함수 실전 예제 (BND 멤버 케미 찾기)
# ==========================================
# 순서가 없는 자료구조인 '집합(Set)'을 사용
# (예: {"리우", "태산"} 과 {"태산", "리우"} 는 완전히 동일하게 취급됨)

def BND(member1, member2):
    pair = {member1, member2}
    
    if pair == {"성호", "명재현"}:
        print("03즈 (명냥즈)")
    elif pair == {"성호", "리우"}:
        print("03즈 (상성즈)")
    elif pair == {"성호", "태산"}:
        print("깜치즈")
    elif pair == {"성호", "이한"}:
        print("물냥즈") 
    elif pair == {"성호", "운학"}:
        print("눈냥즈") 
    elif pair == {"리우", "명재현"}:
        print("개털날리즈 (혁명즈)")
    elif pair == {"리우", "태산"}:
        print("태리우스") 
    elif pair == {"리우", "이한"}:
        print("이리온즈") 
    elif pair == {"리우", "운학"}:
        print("두부즈")
    elif pair == {"태산", "명재현"}:
        print("띵동즈") 
    elif pair == {"명재현", "이한"}:
        print("물멍즈")
    elif pair == {"명재현", "운학"}:
        print("운명즈")
    elif pair == {"태산", "이한"}:
        print("동동즈/04즈")
    elif pair == {"태산", "운학"}:
        print("산학회") 
    elif pair == {"원도어", "보넥도"}:
        print("사랑입니다")
    else:
        print("조합을 찾지 못했습니다 :(((((((")

# 실행 예시
BND("리우", "태산")     # 출력: 태리우스
BND("원도어", "보넥도") # 출력: 사랑입니다
BND("ak", "a")          # 출력: 조합을 찾지 못했습니다 :(((((((

# [보충] 입력 순서를 바꿔도 Set(집합) 덕분에 정상적으로 찾아냅니다!
BND("이한", "성호")     # 출력: 물냥즈
