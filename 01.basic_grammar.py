# 3. 파이썬 기본 작성 규칙 (Naming & Indentation)
# ==========================================

# 3.1 변수 이름 규칙 (Naming Conventions)
# 1. 변수 이름은 영문자(대소문자 구분)나 언더바(_)로 시작해야 합니다. (숫자로 시작 불가)
# 2. 변수 이름에는 영문자, 숫자, 언더바(_)만 포함할 수 있습니다. (공백 및 특수기호 사용 불가)
# 3. 변수 이름은 대소문자를 엄격히 구분합니다. (예: Age와 age는 다른 변수로 취급)
# [추가] 4. 파이썬 예약어(if, for, while, class 등)는 변수 이름으로 사용할 수 없습니다.
# [추가] 5. 권장 사항: 단어와 단어 사이는 언더바로 구분하는 스네이크 케이스(snake_case)를 주로 사용합니다. (예: my_name)

# 3.2 들여쓰기 (Indentation)
# 1. 파이썬에서 들여쓰기는 단순히 보기 좋게 하는 것이 아니라, '코드 블록'을 구분하는 문법적 역할을 합니다. (타 언어의 {} 역할)
# 2. 조건문(if), 반복문(for, while), 함수(def) 등을 작성할 때 하위 블록을 묶어주기 위해 반드시 사용해야 합니다.
# 3. [추가] PEP 8(파이썬 코딩 표준)에서는 들여쓰기에 '공백(Space) 4칸'을 사용하는 것을 가장 권장합니다. 탭(Tab)과 공백을 섞어 쓰면 에러(IndentationError)가 발생할 수 있습니다.
