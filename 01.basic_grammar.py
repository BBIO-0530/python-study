# ------------------------------------------
# 1. 변수와 데이터 타입 (Variables & Data Types)
# ------------------------------------------

# 1.1 정수형 (int): 음수, 0, 양수 모두 사용할 수 있습니다.
x = 10

# 1.2 실수형 (float): 소수점이 있는 숫자로 정밀한 계산에 유용합니다.
y = 5.3

# 1.3 문자열 (str): 문자들의 집합이며 작은따옴표('')나 큰따옴표("")를 사용합니다.
z = "안녕하세요"
name = "성호"

# [보충] 문자열 포매팅: f-string을 사용하여 문자열 내부에 변수를 직관적으로 넣을 수 있습니다.
hello = f"안녕 내 이름은 {name}이야."
print(hello)

# 1.4 불리언 (bool): 참(True) 또는 거짓(False) 두 가지 값만 가질 수 있습니다. (첫 글자는 반드시 대문자)
a = True
print(type(a))  # <class 'bool'> 출력

# 1.5 리스트 (list): 여러 항목을 순서대로 저장하며 대괄호 []를 사용합니다. (값 추가, 수정, 삭제 가능)
BND = ["성호", "리우", "재현"]
print(BND)

# 1.6 튜플 (tuple): 리스트와 유사하지만, 한 번 값을 정하면 변경할 수 없으며 소괄호 ()를 사용합니다.
color = ("red", "blue", "green")

# 1.7 딕셔너리 (dict): 키(Key)와 값(Value)이 한 쌍으로 이루어진 타입입니다. 중괄호 {}를 사용합니다.
BND_age = {"성호": 22, "태산": 21}
print(BND_age["성호"])  # 키를 통해 값을 불러옴 (22 출력)

# 1.8 집합 (set): 순서가 없고 '중복되지 않는' 고유한 값들의 모음입니다. 중괄호 {}를 사용합니다.
age = {1, 2, 3, 4, 5}

# 1.9 None: 변수는 존재하지만 아무런 값도 가지지 않는 '빈(비어있는)' 상태를 의미합니다.
j = None

# ------------------------------------------
# [보충] 타입 변환 (Type Casting)
# ------------------------------------------
h = 15
p = str(h)    # 정수(int)를 문자열(str)로 변환 ("15")
print(type(p))

gr = 10
t = float(gr) # 정수(int)를 실수(float)로 변환 (10.0)
print(t)

# 빠진 내용 추가: 문자열을 정수로 변환
string_num = "20"
num = int(string_num) # 문자열(str)을 정수(int)로 변환 (20)


# ==========================================
# 2. 연산자 (Operators) 및 기본 규칙
# ==========================================

# 2.1 기본 산술 연산자
a = 15
b = 4

print(a + b)   # 덧셈: 19
print(a - b)   # 뺄셈: 11
print(a * b)   # 곱셈: 60
print(a / b)   # 나눗셈: 3.75 (항상 실수형으로 반환)
print(a // b)  # 몫: 3 (소수점 이하 버림)
print(a % b)   # 나머지: 3 (홀수/짝수 판별 등에 자주 쓰임)
print(a ** b)  # 제곱: 50625 (15의 4승)

# 2.2 비교 연산자: 두 값을 비교하여 조건이 맞으면 True, 틀리면 False를 반환합니다.
c = 5
m = 6

print(c == m)  # 같다: 두 값이 같은지 비교 (False)
print(c != m)  # 다르다: 두 값이 다른지 비교 (True)
print(c < m)   # 미만: c가 m보다 작은가? (True)
print(c <= m)  # 이하: c가 m보다 작거나 같은가? (True)
# 빠진 내용 추가 (초과, 이상)
print(c > m)   # 초과: c가 m보다 큰가? (False)
print(c >= m)  # 이상: c가 m보다 크거나 같은가? (False)

# 2.3 논리 연산자: 여러 조건을 결합할 때 사용합니다.
ha = True
ah = False

print(ha and ah) # AND: 둘 다 참(True)일 때만 True 반환 (False)
print(ha or ah)  # OR: 둘 중 하나만 참(True)이어도 True 반환 (True)
print(not ha)    # NOT: 값을 반대로 뒤집음, True면 False, False면 True (False)

