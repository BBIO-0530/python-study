# 코드의 재사용성과 유지보수성을 크게 향상시킬 수 있습니다.


# ------------------------------------------
# 3. 상속 (Inheritance)
# ------------------------------------------
# 기존 클래스(부모)의 기능을 물려받아 새로운 클래스(자식)를 생성하는 방법입니다. 
# 이를 통해 코드의 중복을 줄이고 기존 클래스의 기능을 쉽게 확장할 수 있습니다.
class Animal:
    def __init__(self, codename):
        self.codename = codename

    def Speak(self):
        print(f"**{self.codename} 소리**")

# Animal 클래스를 상속받는 Fox 클래스
class Fox(Animal):
    # [보충] 메서드 오버라이딩 (Overriding)
    # 부모 클래스(Animal)에 있던 Speak() 함수를 무시하고, 자식 클래스(Fox)에서 입맛에 맞게 덮어씌워 재정의하는 기능입니다.
    def Speak(self):
        print(f"{self.codename}은/는 소리를 낸다")

ANIMAL = Fox("영숙이")
ANIMAL.Speak()


