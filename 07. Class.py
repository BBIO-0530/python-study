# 4. 클래스 변수와 인스턴스 변수
# ------------------------------------------
# 클래스 변수는 클래스 전체에서 하나만 공유되며, 
# 인스턴스 변수는 각 객체마다 독립적으로 유지됩니다.

# [보충] 위에서 배운 원칙(첫 글자 대문자)에 맞춰 Circle로 수정
class Circle:
    pi = 3.14  # 클래스 변수: 모든 Circle 객체가 3.14라는 값을 공유합니다.
    
    def __init__(self, radius):
        self.radius = radius  # 인스턴스 변수: 객체마다 반지름(radius) 값이 다릅니다.
        
    def area(self):
        # [보충] 클래스 변수를 사용할 때는 '클래스이름.변수명' (Circle.pi) 형식으로 접근합니다.
        return Circle.pi * (self.radius ** 2)

# [보충] 실행 예시 추가
c = Circle(5)
print(f"반지름이 5인 원의 넓이: {c.area()}")
