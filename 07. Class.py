# ------------------------------------------
# 1. 클래스 (Class)와 객체 (Object)
# ------------------------------------------
# 클래스는 일종의 '설계도'입니다. 
# 이 설계도를 바탕으로 생성된 개별 항목을 객체(Object) 혹은 인스턴스(Instance)라고 합니다.

# [보충] 클래스 이름은 암묵적으로 첫 글자를 대문자로 시작하는 파스칼 케이스(PascalCase)를 사용합니다.
class KOZ: 
    
    # 1.1 생성자 (__init__)
    # 클래스의 생성자로, 객체가 생성될 때 '자동으로' 호출됩니다. 
    # 이를 통해 객체의 초기 속성을 설정할 수 있습니다.
    
    # 1.2 self
    # 생성된 '객체 자신'을 참조하는 변수로, 클래스 내 함수(메서드)에서 반드시 첫 번째 매개변수로 선언해야 합니다.
    def __init__(self, BND, HYBELABLES):
        
        # 1.3 속성 (Attribute)
        # 객체의 상태나 데이터를 저장하는 변수입니다. 
        # 클래스의 생성자(__init__)에서 정의하며 'self.속성이름' 형태로 선언합니다.
        self.BND = BND
        self.HYBELABLES = HYBELABLES
        
    # 1.4 함수 / 메서드 (Method)
    # 객체가 수행할 수 있는 동작을 정의하는 함수입니다.
    # 클래스 내에서 정의되며, 첫 번째 매개변수로 'self'를 사용하여 
    # 해당 객체의 속성에 접근하거나 다른 함수를 호출할 수 있습니다.
    def name(self):
        print(f"{self.BND}(은/는) {self.HYBELABLES}와 KOZ에 소속되어 있습니다.")

# 객체 생성 및 메서드 호출
a = KOZ("Taesan", "HYBE LABELS")
a.name()


