# ------------------------------------------
# 조건문 (Conditional Statements)
# ------------------------------------------
# 특정 조건이 충족될 때(True)만 특정 코드가 실행되게 하는 문법입니다.
# [보충] 파이썬에서는 조건문 아래에 실행할 코드를 작성할 때 반드시 '들여쓰기(공백 4칸)'를 해야 합니다.

# [보충] input() 함수: 사용자에게 질문을 던지고, 입력한 값을 '문자열(str)' 형태로 변수 안에 저장합니다.

# ------------------------------------------
# 1. if 문
# ------------------------------------------
# 조건이 참(True)일 때만 들여쓰기 된 코드가 실행됩니다. 거짓(False)이면 그냥 넘어갑니다.
name = input("BND를 좋아하십니까?? (예/아니오) : ")

if name == "예":
    # name 변수의 값이 "예"와 같을 때만 아래 문장이 출력됩니다.
    print("혹시 덕메 가능하실까요? :))")


# ------------------------------------------
# 2. if-else 문
# ------------------------------------------
# 조건이 참일 때 실행할 코드와, 거짓일 때(그 외의 모든 경우) 실행할 코드를 나눌 수 있습니다.
fan_or_not = input("onedoor이실 경우 'onedoor'를 입력해주십시오 : ")

if fan_or_not == "onedoor":
    print("지금부터 저의 덕메가 되셨습니다.")
else:
    # 입력한 값이 "onedoor"가 아닌 모든 경우에 아래 문장이 출력됩니다.
    print("BND 태산 얼윈파 직캠 한번 보실래요??")


# ------------------------------------------
# 3. if-elif-else 문
# ------------------------------------------
# 여러 개의 조건을 순차적으로 검사해야 할 때 사용합니다.
# elif는 'else if'의 줄임말로, 원하는 만큼 여러 번 사용할 수 있습니다.
if fan_or_not == "onedoor":
    print("지금부터 저의 덕메가 되셨습니다.")
elif fan_or_not == "잼도어":
    # 첫 번째 조건(onedoor)이 거짓이고, 두 번째 조건(잼도어)이 참일 때 실행됩니다.
    print("예의 좀 갖추시길요;;")
else:
    # 위의 모든 조건이 거짓일 때 실행됩니다.
    print("BND 태산 얼윈파 직캠 한번 보실래요??")


# ------------------------------------------
# 4. 중첩 조건문 (Nested if)
# ------------------------------------------
# 조건문 안에 또 다른 조건문을 넣을 수 있습니다. 세부적인 조건을 나눌 때 유용합니다.
music = input("Spotify로 음악을 들으시나요, YouTube Music으로 들으시나요?? : ")

if music == "Spotify":
    # 바깥쪽 조건이 참일 때만 안쪽 질문을 물어봅니다.
    # [보충] 중첩될수록 들여쓰기가 한 번 더(공백 8칸) 들어갑니다.
    Q2 = input("premium 요금제인가요, 아니면 free 요금제인가요?? : ")
    
    if Q2 == "premium":
        print("와 돈 많으시다!")
    elif Q2 == "free":
        print("광고 듣기 귀찮지 않으신가요?")
else:
    print("저도 음악 듣는 거 좋아해요!")
