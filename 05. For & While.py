# 반복문
# 코드를 여러번 실행하고 싶을 때 사용하는 문법이다.
#for문
#for문은 주로 리스트, 문자열, 튜플 등과 같은 각 항목에 순서대로 접근해야 할때 사용합니다.
BND=["onedoor","members","ZICO"]
for i in BND:
    print(i)
#range 함수
#for문에서 반복 횟수를 지정해줄 수 있는 함수이다.
for a in range(10):
    print("BND the G.O.A.T")
