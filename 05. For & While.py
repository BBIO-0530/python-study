# ------------------------------------------
# 반복문 (Loops)
# ------------------------------------------
# 똑같은 코드나 비슷한 패턴의 코드를 여러 번 실행하고 싶을 때 사용하는 문법입니다.


# ------------------------------------------
# 1. for 문
# ------------------------------------------
# for문은 주로 리스트, 문자열, 튜플 등에 들어있는 각 항목을 '처음부터 끝까지 순서대로' 꺼내 쓸 때 사용합니다.
BND = ["onedoor", "members", "ZICO"]

for i in BND:
    # [보충] 변수 i에는 BND 리스트의 항목들이 한 번에 하나씩 차례대로 담깁니다. (이름은 i 말고 마음대로 지어도 됩니다!)
    print(i)


# ------------------------------------------
# 2. range() 함수
# ------------------------------------------
# for문에서 '반복 횟수'를 숫자로 직접 지정해 줄 수 있는 아주 유용한 함수입니다.
for a in range(10):
    print("BND the G.O.A.T") # 0부터 9까지 총 10번 출력됩니다.

# [기본 사용법 정리]
# 1. range(stop) : 0부터 stop-1 까지의 숫자를 생성합니다.
# 2. range(start, stop) : start부터 stop-1 까지의 숫자를 생성합니다.
# 3. range(start, stop, step) : 증가폭(step)을 지정할 수 있습니다.

# [보충] 시작점, 끝점, 증가폭 예시
for b in range(1, 10, 2):
    print(b) # 1부터 9까지 2씩 증가하며 출력 (1, 3, 5, 7, 9)

# [보충] 감소폭 지정 예시 (역순 카운트다운)
for c in range(5, 0, -1):
    print(c) # 5부터 1까지 1씩 감소하며 출력 (5, 4, 3, 2, 1)


# ------------------------------------------
# 3. while 문
# ------------------------------------------
# 조건이 '참(True)'인 동안 계속해서 반복하고, 조건이 '거짓(False)'이 되면 반복을 끝내는 문법입니다.
count = 0
while count < 10:
    print(count)
    count += 1  # [보충] 이 코드가 없으면 count가 영원히 0이라서 무한 루프(Infinite Loop)에 빠집니다! 주의!

# [무한 루프 예시]
# while True:
#    print("난 돈이 좋아") 
# (주석을 풀고 실행하면 프로그램이 멈추지 않고 계속 실행됩니다. 강제 종료해야 함)


# ------------------------------------------
# 4. 반복문 제어 (break, continue, else)
# ------------------------------------------

# 4.1 break: 특정 조건을 만족하면 반복문을 '즉시 완전히 종료'합니다.
for k in range(1, 10):
    if k == 5:
        break  # k가 5가 되는 순간 반복문을 탈출!
    print(k)   # 1, 2, 3, 4 까지만 출력됨

print("---") # 구분선

# 4.2 continue: 현재 반복만 건너뛰고, '다음 반복'으로 바로 넘어갑니다.
# 4.3 else (반복문과 함께 쓰일 때): break로 강제 종료되지 않고 반복문이 끝까지 '정상적으로' 다 돌았을 때 딱 한 번 실행됩니다.
for l in range(10):
    if l == 4 or l == 6:
        continue  # l이 4이거나 6일 때는 아래 print(l)을 무시하고 바로 다음 숫자로 넘어갑니다.
    print(l)      # 0, 1, 2, 3, 5, 7, 8, 9 출력
else:
    print("돈이 최고야 (정상적으로 반복문 종료됨!)")


# ------------------------------------------
# 5. 중첩 반복문 (Nested Loops)
# ------------------------------------------
# 반복문 안에 또 다른 반복문이 들어있는 구조입니다. (구구단 만들 때 대표적으로 쓰임)
# [보충] 바깥쪽 반복문이 1번 도는 동안, 안쪽 반복문은 자신의 전체 횟수를 다 돕니다.
for i in range(2, 10):       # 2단부터 9단까지 (바깥 루프)
    for j in range(1, 10):   # 1부터 9까지 곱하기 (안쪽 루프)
        print(f"{i} x {j} = {i * j}")
    print("-")               # 각 단이 끝날 때마다 하이픈 출력


# ------------------------------------------
# 6. len() 함수 사용법
# ------------------------------------------
# [보충] len()은 길이나 개수를 알려주는 함수입니다. 
# 리스트/딕셔너리를 넣으면 '데이터의 개수'를 반환하고, 문자열을 넣으면 '글자 수'를 반환합니다.
members = ["박성호", "리우", "명재현", "태산", "이한", "김운학"]

print("==== 이름이 두 글자인 멤버 ====")
for BND in members:
    # 멤버 이름(문자열)의 글자 수가 2로 나누어 떨어지는지(짝수인지) 검사합니다.
    if len(BND) % 2 == 0:
        print(BND)  # 리우, 태산, 이한 출력

print("==== 리더 찾기 ====")
for BND in members:
    if BND == "명재현":
        print(f"{BND} : leader")
